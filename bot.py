user_states: dict[int, dict] = {}

def get_state(uid: int) -> dict:
    if uid not in user_states:
        user_states[uid] = {
            "score": 0,
            "scene": "start",
            "path": None,
            "answered": set(),
        }
    return user_states[uid]

def reset_state(uid: int):
    user_states[uid] = {
        "score": 0,
        "scene": "start",
        "path": None,
        "answered": set(),
    }

